TEST_CASE(invalid_string_escape)
{
    struct token_list tokens;

    CHECK_STR_EQ(dump_types("\"a\\qb\""), "ERROR EOF");

    tokens = lex_all("\"a\\qb\"");
    REQUIRE(tokens.count == 2U);
    CHECK_EQ(tokens.items[0].error, TRACEY_TOKEN_ERROR_INVALID_ESCAPE);
    CHECK(token_lexeme_is(&tokens.items[0], "\\q"));
    CHECK_EQ(tokens.items[0].line, 1U);
    CHECK_EQ(tokens.items[0].column, 3U);

    /* The string is consumed to its closing quote, so lexing continues. */
    CHECK_STR_EQ(dump_types("\"a\\qb\" x"), "ERROR IDENTIFIER EOF");
    token_list_destroy(&tokens);
}

TEST_CASE(unterminated_string)
{
    struct token_list tokens;

    CHECK_STR_EQ(dump_types("\"abc"), "ERROR EOF");

    tokens = lex_all("\"abc");
    REQUIRE(tokens.count == 2U);
    CHECK_EQ(tokens.items[0].error, TRACEY_TOKEN_ERROR_UNTERMINATED_STRING);
    CHECK_EQ(tokens.items[0].column, 1U);

    /* Strings do not span lines: the next line still lexes normally. */
    CHECK_STR_EQ(dump_types("\"abc\nx"), "ERROR IDENTIFIER EOF");

    token_list_destroy(&tokens);
    tokens = lex_all("\"abc\nx");
    REQUIRE(tokens.count == 3U);
    CHECK_EQ(tokens.items[1].line, 2U);
    CHECK_EQ(tokens.items[1].column, 1U);
    token_list_destroy(&tokens);
}

TEST_CASE(recovery_continues_after_errors)
{
    struct token_list tokens;

    CHECK_STR_EQ(dump_types("a @ b # c"),
                 "IDENTIFIER ERROR IDENTIFIER ERROR IDENTIFIER EOF");

    tokens = lex_all("a @ b # c");
    REQUIRE(tokens.count == 6U);
    CHECK_EQ(tokens.items[1].error, TRACEY_TOKEN_ERROR_INVALID_CHARACTER);
    CHECK(token_lexeme_is(&tokens.items[1], "@"));
    CHECK_EQ(tokens.items[1].column, 3U);
    CHECK_EQ(tokens.items[3].error, TRACEY_TOKEN_ERROR_INVALID_CHARACTER);
    CHECK(token_lexeme_is(&tokens.items[3], "#"));
    CHECK_EQ(tokens.items[3].column, 7U);
    token_list_destroy(&tokens);
}

TEST_CASE(token_validity_helpers)
{
    struct token_list tokens = lex_all("@");

    REQUIRE(tokens.count == 2U);
    CHECK(tracey_token_is_error(&tokens.items[0]));
    /* valid() is the inverse of is_error(); both forms are asserted to
     * keep the coverage of the original test. */
    CHECK_FALSE(!tracey_token_is_error(&tokens.items[0]));
    CHECK(!tracey_token_is_error(&tokens.items[1]));
    CHECK_FALSE(tracey_token_is_error(&tokens.items[1]));

    token_list_destroy(&tokens);
}

TEST_CASE(peek_does_not_consume)
{
    struct tracey_lexer lexer;
    struct tracey_token peek1;
    struct tracey_token peek2;
    struct tracey_token next1;
    struct tracey_token peek3;
    struct tracey_token next2;
    struct tracey_token next3;

    tracey_lexer_init(&lexer, "a b", 3);

    peek1 = tracey_lexer_peek(&lexer);
    peek2 = tracey_lexer_peek(&lexer);
    CHECK_EQ(peek1.type, TRACEY_TOKEN_IDENTIFIER);
    CHECK_EQ(peek2.type, TRACEY_TOKEN_IDENTIFIER);
    CHECK(token_lexeme_is(&peek1, "a"));
    CHECK(token_lexeme_is(&peek2, "a"));

    next1 = tracey_lexer_next(&lexer);
    CHECK_EQ(next1.type, TRACEY_TOKEN_IDENTIFIER);
    CHECK(token_lexeme_is(&next1, "a"));

    peek3 = tracey_lexer_peek(&lexer);
    CHECK(token_lexeme_is(&peek3, "b"));

    next2 = tracey_lexer_next(&lexer);
    CHECK(token_lexeme_is(&next2, "b"));

    next3 = tracey_lexer_next(&lexer);
    CHECK_EQ(next3.type, TRACEY_TOKEN_EOF);
    CHECK(tracey_lexer_is_at_end(&lexer));
}

TEST_CASE(fuzz_lite_arbitrary_bytes_never_crash_or_escape_source)
{
    /*
     * Deterministic LCG: the same byte stream is produced on every
     * platform and run. len is bounded to 127 so the fixed buffer is
     * always large enough and every source pointer stays inside it.
     */
    uint64_t state = 0x0DDB1A5E5BAD5EEDULL;
    int round;

    for (round = 0; round < 200; round++)
    {
        char src[128];
        size_t len = (size_t)((fuzz_step(&state) >> 17U) % 128U);
        size_t produced = 0;
        size_t i;
        struct tracey_lexer lexer;
        struct tracey_token eof;

        for (i = 0; i < len; i++)
            src[i] = (char)((fuzz_step(&state) >> 33U) & 0xFFU);

        tracey_lexer_init(&lexer, src, len);

        for (;;)
        {
            struct tracey_token token = tracey_lexer_next(&lexer);

            produced++;
            if (token.type == TRACEY_TOKEN_EOF)
                break;

            /* Every lexeme must be a view inside the source buffer. */
            REQUIRE(token.lexeme != NULL);
            REQUIRE(token.lexeme >= src);
            REQUIRE(token.lexeme + token.lexeme_len <= src + len);

            /* At least one byte is consumed per token, so a stream can
             * never be longer than the input. */
            REQUIRE(produced <= len + 1U);
        }

        /* EOF is stable: asking again still yields EOF. */
        eof = tracey_lexer_next(&lexer);
        CHECK_EQ(eof.type, TRACEY_TOKEN_EOF);
    }
}

