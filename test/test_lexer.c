TEST_CASE(block_comments)
{
    struct token_list tokens;

    CHECK_STR_EQ(dump_types("x /* one\ntwo */ y"), "IDENTIFIER IDENTIFIER EOF");
    CHECK_STR_EQ(dump_types("/**/"), "EOF");
    CHECK_STR_EQ(dump_types("/* two /* is not nested */ x"), "IDENTIFIER EOF");

    /* The token after a multi-line comment has correct line/column. */
    tokens = lex_all("x /* one\ntwo */ y");
    REQUIRE(tokens.count == 3U);
    CHECK_EQ(tokens.items[1].line, 2U);
    CHECK_EQ(tokens.items[1].column, 8U);

    /* A comment can stand in for the whitespace around operators. */
    CHECK_STR_EQ(dump_types("a/* c */+/* c */b"),
                 "IDENTIFIER PLUS IDENTIFIER EOF");
    token_list_destroy(&tokens);
}

TEST_CASE(unterminated_block_comment)
{
    struct token_list tokens;

    CHECK_STR_EQ(dump_types("/* nope"), "ERROR EOF");
    CHECK_STR_EQ(dump_types("x /* nope"), "IDENTIFIER ERROR EOF");

    tokens = lex_all("x\n  /* nope");
    REQUIRE(tokens.count == 3U);
    CHECK_EQ(tokens.items[1].error, TRACEY_TOKEN_ERROR_UNTERMINATED_COMMENT);
    CHECK_EQ(tokens.items[1].line, 2U);
    CHECK_EQ(tokens.items[1].column, 3U);
    token_list_destroy(&tokens);
}

