/*
 * Lexer unit tests.
 *
 * These cases exercise the public lexer interface declared in
 * <tracey/lexer.h>. Every program is lexed to EOF; the helpers below
 * collect tokens into a fixed-capacity array owned by the caller and
 * render token streams as "TYPE TYPE ..." strings for whole-program shape
 * assertions.
 *
 * The lexer does not allocate and its tokens reference the input buffer,
 * so the source literals used here stay alive for the duration of each
 * case. No allocation outlives a test case except the temporary token
 * arrays, which are released with token_list_destroy.
 */

#include "test_harness.h"

#include <tracey/lexer.h>

#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/*
 * Owned array of tokens produced by lex_all.
 *
 * items is a heap allocation of at least count entries; count includes the
 * terminating EOF token. The token lexemes reference the source buffer
 * passed to lex_all and are not valid after that buffer is released.
 */
struct token_list
{
    struct tracey_token *items;
    size_t count;
};

/*
 * lex_all - lex a NUL-terminated source string through the EOF token.
 *
 * src must be a valid NUL-terminated string whose bytes remain valid while
 * the returned tokens are inspected. The returned list owns its array and
 * must be released with token_list_destroy.
 *
 * The allocation is sized from the input length: a conforming lexer emits
 * at most one token per input byte plus the EOF token. If the lexer ever
 * exceeds that bound the loop stops instead of overflowing the array, which
 * lets the assertion in the caller report the runaway stream rather than
 * crashing the test binary. Allocation failure aborts the process because
 * the test run cannot produce meaningful results without the token array.
 */
static struct token_list lex_all(const char *src)
{
    struct token_list list;
    struct tracey_lexer lexer;
    size_t len = strlen(src);
    size_t capacity = len + 1;

    list.items = (struct tracey_token *)malloc(capacity * sizeof(*list.items));
    if (list.items == NULL)
    {
        fputs("test_lexer: out of memory\n", stderr);
        exit(EXIT_FAILURE);
    }
    list.count = 0;

    tracey_lexer_init(&lexer, src, len);
    for (;;)
    {
        struct tracey_token token;

        if (list.count >= capacity)
            break;

        token = tracey_lexer_next(&lexer);
        list.items[list.count] = token;
        list.count++;

        if (token.type == TRACEY_TOKEN_EOF)
            break;
    }

    return list;
}

/*
 * token_list_destroy - release the token array owned by list.
 */
static void token_list_destroy(struct token_list *list)
{
    free(list->items);
    list->items = NULL;
    list->count = 0;
}

/*
 * token_lexeme_is - compare a token lexeme against a C string.
 *
 * The lexeme is not NUL-terminated, so the comparison uses the recorded
 * length and memcmp. Returns false for a NULL lexeme or a length mismatch.
 */
static bool token_lexeme_is(const struct tracey_token *token, const char *text)
{
    size_t len = strlen(text);

    if (token->lexeme == NULL || token->lexeme_len != len)
        return false;
    return memcmp(token->lexeme, text, len) == 0;
}

/*
 * dump_types - render a token stream as space-separated type names.
 *
 * The result points into a static buffer that is reused by every call, so
 * a caller must consume the string before invoking dump_types again. Inputs
 * in these tests are short; the buffer is sized generously and truncation
 * simply shortens the rendered stream instead of overflowing.
 */
static const char *dump_types(const char *src)
{
    static char out[4096];
    struct token_list list = lex_all(src);
    size_t used = 0;
    size_t i;

    out[0] = '\0';
    for (i = 0; i < list.count; i++)
    {
        const char *name = tracey_token_type_string(list.items[i].type);
        int written = snprintf(out + used, sizeof(out) - used, "%s%s",
                               i == 0 ? "" : " ", name);

        if (written < 0)
            break;
        if ((size_t)written >= sizeof(out) - used)
        {
            used = sizeof(out) - 1;
            break;
        }
        used += (size_t)written;
    }

    token_list_destroy(&list);
    return out;
}

/*
 * fuzz_step - advance the deterministic LCG used by the fuzz-lite case.
 *
 * The constants are the 64-bit LCG recommended by Knuth; updating state in
 * place makes the generated byte stream identical on every platform and
 * run, which keeps the test reproducible.
 */
static uint64_t fuzz_step(uint64_t *state)
{
    *state = *state * 6364136223846793005ULL + 1442695040888963407ULL;
    return *state;
}

TEST_CASE(basic_program_tokenizes)
{
    CHECK_STR_EQ(dump_types("int main() {\n    return 0;\n}"),
                 "KEYWORD_INT IDENTIFIER LPAREN RPAREN LBRACE "
                 "KEYWORD_RETURN INTEGER SEMICOLON RBRACE EOF");
}

TEST_CASE(line_and_column_tracking)
{
    struct token_list tokens = lex_all("ab\n  cd\r\nef");

    REQUIRE(tokens.count == 4U);
    CHECK(token_lexeme_is(&tokens.items[0], "ab"));
    CHECK_EQ(tokens.items[0].line, 1U);
    CHECK_EQ(tokens.items[0].column, 1U);
    CHECK(token_lexeme_is(&tokens.items[1], "cd"));
    CHECK_EQ(tokens.items[1].line, 2U);
    CHECK_EQ(tokens.items[1].column, 3U);
    CHECK(token_lexeme_is(&tokens.items[2], "ef"));
    CHECK_EQ(tokens.items[2].line, 3U);
    CHECK_EQ(tokens.items[2].column, 1U);
    CHECK_EQ(tokens.items[3].type, TRACEY_TOKEN_EOF);
    CHECK_EQ(tokens.items[3].line, 3U);
    CHECK_EQ(tokens.items[3].column, 3U);

    token_list_destroy(&tokens);
}

TEST_CASE(tabs_count_as_one_column)
{
    struct token_list tokens = lex_all("\tx");

    REQUIRE(tokens.count == 2U);
    CHECK_EQ(tokens.items[0].column, 2U);

    token_list_destroy(&tokens);
}

TEST_CASE(empty_and_whitespace_only_input)
{
    struct token_list tokens;

    CHECK_STR_EQ(dump_types(""), "EOF");
    CHECK_STR_EQ(dump_types("   \t\r\n  "), "EOF");

    tokens = lex_all("");
    CHECK_EQ(tokens.items[0].line, 1U);
    CHECK_EQ(tokens.items[0].column, 1U);
    token_list_destroy(&tokens);
}

