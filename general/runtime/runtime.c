#include "tracey/runtime.h"

void tracey_emit_runtime_helpers(FILE *out, enum tracey_target_arch arch)
{
    if (out == NULL || arch != TRACEY_TARGET_AARCH64)
        return;

    fprintf(out, "    .globl __tracey_print_int\n");
    fprintf(out, "__tracey_print_int:\n");
    fprintf(out, "    sub sp, sp, #32\n");
    fprintf(out, "    mov x1, #0\n");
    fprintf(out, "    cmp x0, #0\n");
    fprintf(out, "    b.ge Lpi_pos\n");
    fprintf(out, "    neg x0, x0\n");
    fprintf(out, "    mov x1, #1\n");
    fprintf(out, "Lpi_pos:\n");
    fprintf(out, "    add x2, sp, #31\n");
    fprintf(out, "    mov w3, #0\n");
    fprintf(out, "    strb w3, [x2]\n");
    fprintf(out, "    mov x4, #0\n");
    fprintf(out, "Lpi_loop:\n");
    fprintf(out, "    mov x5, #10\n");
    fprintf(out, "    udiv x6, x0, x5\n");
    fprintf(out, "    msub x7, x6, x5, x0\n");
    fprintf(out, "    add w7, w7, #48\n");
    fprintf(out, "    sub x2, x2, #1\n");
    fprintf(out, "    strb w7, [x2]\n");
    fprintf(out, "    add x4, x4, #1\n");
    fprintf(out, "    mov x0, x6\n");
    fprintf(out, "    cbnz x0, Lpi_loop\n");
    fprintf(out, "    cbz x1, Lpi_nosign\n");
    fprintf(out, "    sub x2, x2, #1\n");
    fprintf(out, "    mov w3, #45\n");
    fprintf(out, "    strb w3, [x2]\n");
    fprintf(out, "    add x4, x4, #1\n");
    fprintf(out, "Lpi_nosign:\n");
    fprintf(out, "    mov x8, #64\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    mov x1, x2\n");
    fprintf(out, "    mov x2, x4\n");
    fprintf(out, "    svc #0\n");
    fprintf(out, "    add sp, sp, #32\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_print_str\n");
    fprintf(out, "__tracey_print_str:\n");
    fprintf(out, "    mov x1, x0\n");
    fprintf(out, "    mov x2, x0\n");
    fprintf(out, "Lps_len:\n");
    fprintf(out, "    ldrb w3, [x1]\n");
    fprintf(out, "    cbz w3, Lps_done\n");
    fprintf(out, "    add x1, x1, #1\n");
    fprintf(out, "    b Lps_len\n");
    fprintf(out, "Lps_done:\n");
    fprintf(out, "    sub x2, x1, x2\n");
    fprintf(out, "    mov x1, x0\n");
    fprintf(out, "    mov x8, #64\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    svc #0\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_input_int\n");
    fprintf(out, "__tracey_input_int:\n");
    fprintf(out, "    stp x29, x30, [sp, #-16]!\n");
    fprintf(out, "    stp x19, x20, [sp, #-16]!\n");
    fprintf(out, "    stp x21, x22, [sp, #-16]!\n");
    fprintf(out, "    mov x19, #0\n");
    fprintf(out, "    mov x20, #0\n");
    fprintf(out, "    mov x21, #0\n");
    fprintf(out, "Li_int_skipws:\n");
    fprintf(out, "    bl __tracey_read_byte\n");
    fprintf(out, "    cbz x1, Li_int_eof\n");
    fprintf(out, "    cmp x0, #32\n");
    fprintf(out, "    beq Li_int_skipws\n");
    fprintf(out, "    cmp x0, #9\n");
    fprintf(out, "    beq Li_int_skipws\n");
    fprintf(out, "    cmp x0, #10\n");
    fprintf(out, "    beq Li_int_skipws\n");
    fprintf(out, "    cmp x0, #13\n");
    fprintf(out, "    beq Li_int_skipws\n");
    fprintf(out, "    cmp x0, #45\n");
    fprintf(out, "    beq Li_int_minus\n");
    fprintf(out, "    sub x22, x0, #48\n");
    fprintf(out, "    cmp x22, #9\n");
    fprintf(out, "    cset x23, ls\n");
    fprintf(out, "    cbz x23, Li_int_invalid\n");
    fprintf(out, "    mov x19, x22\n");
    fprintf(out, "    mov x21, #1\n");
    fprintf(out, "    b Li_int_loop\n");
    fprintf(out, "Li_int_minus:\n");
    fprintf(out, "    mov x20, #1\n");
    fprintf(out, "    mov x21, #1\n");
    fprintf(out, "Li_int_loop:\n");
    fprintf(out, "    bl __tracey_read_byte\n");
    fprintf(out, "    cbz x1, Li_int_done\n");
    fprintf(out, "    sub x22, x0, #48\n");
    fprintf(out, "    cmp x22, #9\n");
    fprintf(out, "    cset x23, ls\n");
    fprintf(out, "    cbz x23, Li_int_done\n");
    fprintf(out, "    mov x2, #10\n");
    fprintf(out, "    mul x3, x19, x2\n");
    fprintf(out, "    add x19, x3, x22\n");
    fprintf(out, "    mov x21, #1\n");
    fprintf(out, "    b Li_int_loop\n");
    fprintf(out, "Li_int_invalid:\n");
    fprintf(out, "    mov x19, #0\n");
    fprintf(out, "    mov x20, #0\n");
    fprintf(out, "    mov x21, #0\n");
    fprintf(out, "Li_int_done:\n");
    fprintf(out, "    cbz x21, Li_int_zero\n");
    fprintf(out, "    cbz x20, Li_int_ret\n");
    fprintf(out, "    neg x19, x19\n");
    fprintf(out, "Li_int_ret:\n");
    fprintf(out, "    mov x0, x19\n");
    fprintf(out, "    ldp x21, x22, [sp], #16\n");
    fprintf(out, "    ldp x19, x20, [sp], #16\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Li_int_zero:\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    ldp x21, x22, [sp], #16\n");
    fprintf(out, "    ldp x19, x20, [sp], #16\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Li_int_eof:\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    ldp x21, x22, [sp], #16\n");
    fprintf(out, "    ldp x19, x20, [sp], #16\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_input_str\n");
    fprintf(out, "__tracey_input_str:\n");
    fprintf(out, "    stp x29, x30, [sp, #-16]!\n");
    fprintf(out, "    cmp x0, #0\n");
    fprintf(out, "    beq Li_str_invalid\n");
    fprintf(out, "    cmp x1, #1\n");
    fprintf(out, "    cset x2, lt\n");
    fprintf(out, "    cbnz x2, Li_str_invalid\n");
    fprintf(out, "    stp x19, x20, [sp, #-16]!\n");
    fprintf(out, "    stp x21, x22, [sp, #-16]!\n");
    fprintf(out, "    mov x19, x0\n");
    fprintf(out, "    mov x20, x1\n");
    fprintf(out, "    mov x21, #0\n");
    fprintf(out, "Li_str_loop:\n");
    fprintf(out, "    sub x22, x20, #1\n");
    fprintf(out, "    cmp x21, x22\n");
    fprintf(out, "    cset x2, ge\n");
    fprintf(out, "    cbnz x2, Li_str_term\n");
    fprintf(out, "    bl __tracey_read_byte\n");
    fprintf(out, "    cbz x1, Li_str_term\n");
    fprintf(out, "    cmp x0, #10\n");
    fprintf(out, "    beq Li_str_term\n");
    fprintf(out, "    add x2, x19, x21\n");
    fprintf(out, "    strb w0, [x2]\n");
    fprintf(out, "    add x21, x21, #1\n");
    fprintf(out, "    b Li_str_loop\n");
    fprintf(out, "Li_str_term:\n");
    fprintf(out, "    mov w3, #0\n");
    fprintf(out, "    add x2, x19, x21\n");
    fprintf(out, "    strb w3, [x2]\n");
    fprintf(out, "    mov x0, x21\n");
    fprintf(out, "    ldp x21, x22, [sp], #16\n");
    fprintf(out, "    ldp x19, x20, [sp], #16\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Li_str_invalid:\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_putchar\n");
    fprintf(out, "__tracey_putchar:\n");
    fprintf(out, "    sub sp, sp, #16\n");
    fprintf(out, "    strb w0, [sp]\n");
    fprintf(out, "    mov x8, #64\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    mov x1, sp\n");
    fprintf(out, "    mov x2, #1\n");
    fprintf(out, "    svc #0\n");
    fprintf(out, "    ldrb w0, [sp]\n");
    fprintf(out, "    add sp, sp, #16\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_getchar\n");
    fprintf(out, "__tracey_getchar:\n");
    fprintf(out, "    sub sp, sp, #16\n");
    fprintf(out, "    mov x8, #63\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    mov x1, sp\n");
    fprintf(out, "    mov x2, #1\n");
    fprintf(out, "    svc #0\n");
    fprintf(out, "    cmp x0, #1\n");
    fprintf(out, "    b.ne Lgc_eof\n");
    fprintf(out, "    ldrb w0, [sp]\n");
    fprintf(out, "    add sp, sp, #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Lgc_eof:\n");
    fprintf(out, "    mov x0, #-1\n");
    fprintf(out, "    add sp, sp, #16\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_puts\n");
    fprintf(out, "__tracey_puts:\n");
    fprintf(out, "    mov x1, x0\n");
    fprintf(out, "    mov x2, x0\n");
    fprintf(out, "Lputs_len:\n");
    fprintf(out, "    ldrb w3, [x1]\n");
    fprintf(out, "    cbz w3, Lputs_done\n");
    fprintf(out, "    add x1, x1, #1\n");
    fprintf(out, "    b Lputs_len\n");
    fprintf(out, "Lputs_done:\n");
    fprintf(out, "    sub x2, x1, x2\n");
    fprintf(out, "    mov x1, x0\n");
    fprintf(out, "    mov x8, #64\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    svc #0\n");
    /* print newline */
    fprintf(out, "    sub sp, sp, #16\n");
    fprintf(out, "    mov w3, #10\n");
    fprintf(out, "    strb w3, [sp]\n");
    fprintf(out, "    mov x8, #64\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    mov x1, sp\n");
    fprintf(out, "    mov x2, #1\n");
    fprintf(out, "    svc #0\n");
    fprintf(out, "    add sp, sp, #16\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_fget\n");
    fprintf(out, "__tracey_fget:\n");
    fprintf(out, "    stp x29, x30, [sp, #-16]!\n");
    fprintf(out, "    cbz x0, Lfget_invalid\n");
    fprintf(out, "    mov x19, x0\n");
    fprintf(out, "    mov x20, #0\n");
    fprintf(out, "Lfget_loop:\n");
    fprintf(out, "    bl __tracey_read_byte\n");
    fprintf(out, "    cbz x1, Lfget_term\n");
    fprintf(out, "    cmp x0, #10\n");
    fprintf(out, "    beq Lfget_term\n");
    fprintf(out, "    strb w0, [x19, x20]\n");
    fprintf(out, "    add x20, x20, #1\n");
    fprintf(out, "    b Lfget_loop\n");
    fprintf(out, "Lfget_term:\n");
    fprintf(out, "    strb wzr, [x19, x20]\n");
    fprintf(out, "    mov x0, x19\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Lfget_invalid:\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_scanf\n");
    fprintf(out, "__tracey_scanf:\n");
    fprintf(out, "    stp x29, x30, [sp, #-16]!\n");
    fprintf(out, "    mov x19, x1\n");
    fprintf(out, "    ldrb w2, [x0, #1]\n");
    fprintf(out, "    cmp w2, #100\n"); /* 'd' */
    fprintf(out, "    beq Lscanf_d\n");
    fprintf(out, "    mov x0, x19\n");
    fprintf(out, "    mov x1, #256\n");
    fprintf(out, "    bl __tracey_input_str\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Lscanf_d:\n");
    fprintf(out, "    bl __tracey_input_int\n");
    fprintf(out, "    str x0, [x19]\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_scanfs\n");
    fprintf(out, "__tracey_scanfs:\n");
    fprintf(out, "    stp x29, x30, [sp, #-16]!\n");
    fprintf(out, "    mov x19, x1\n");
    fprintf(out, "    mov x20, x2\n");
    fprintf(out, "    ldrb w3, [x0, #1]\n");
    fprintf(out, "    cmp w3, #100\n"); /* 'd' */
    fprintf(out, "    beq Lscanfs_d\n");
    fprintf(out, "    mov x0, x19\n");
    fprintf(out, "    mov x1, x20\n");
    fprintf(out, "    bl __tracey_input_str\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Lscanfs_d:\n");
    fprintf(out, "    bl __tracey_input_int\n");
    fprintf(out, "    str x0, [x19]\n");
    fprintf(out, "    mov x0, #1\n");
    fprintf(out, "    ldp x29, x30, [sp], #16\n");
    fprintf(out, "    ret\n");

    fprintf(out, "    .globl __tracey_read_byte\n");
    fprintf(out, "__tracey_read_byte:\n");
    fprintf(out, "    sub sp, sp, #16\n");
    fprintf(out, "    mov x8, #63\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    mov x1, sp\n");
    fprintf(out, "    mov x2, #1\n");
    fprintf(out, "    svc #0\n");
    fprintf(out, "    cmp x0, #1\n");
    fprintf(out, "    beq Li_rb_ok\n");
    fprintf(out, "Li_rb_eof:\n");
    fprintf(out, "    mov x1, #0\n");
    fprintf(out, "    mov x0, #0\n");
    fprintf(out, "    add sp, sp, #16\n");
    fprintf(out, "    ret\n");
    fprintf(out, "Li_rb_ok:\n");
    fprintf(out, "    ldrb w0, [sp]\n");
    fprintf(out, "    mov x1, #1\n");
    fprintf(out, "    add sp, sp, #16\n");
    fprintf(out, "    ret\n");
}
